import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { demoFrame } from "../figma/fixtures";
const root = new URL("../", import.meta.url);
const required = ["LICENSE", "THIRD_PARTY_NOTICES.md", "SECURITY.md", "CONTRIBUTING.md", "CHANGELOG.md", ".github/workflows/ci.yml", "samples/demo.ir.json", "studio/src/Crisp.luau", "studio/src/ImageKey.luau", "studio/src/Protocol.luau", "studio/src/ImportAction.luau"];
for (const file of required) if (!existsSync(new URL(file, root))) throw new Error("Release file missing: " + file);
const extract = (await Bun.file(new URL("figma/extract.js", root)).text()).replace(/^if \(typeof module.*$/m, "");
const main = await Bun.file(new URL("figma/plugin/main.js", root)).text();
const expected = `// Generated by tools/build_figma.ts. Edit extract.js / plugin/main.js instead.\n${extract}\n${main}`;
if (await Bun.file(new URL("figma/plugin/code.js", root)).text() !== expected) throw new Error("Generated Figma code is stale; run bun tools/build_figma.ts");
const uiTemplate = await Bun.file(new URL("figma/plugin/ui.source.html", root)).text();
const guideScript = await Bun.file(new URL("figma/plugin/tag-guide.js", root)).text();
const guideStyle = await Bun.file(new URL("figma/plugin/tag-guide.css", root)).text();
const expectedUI = uiTemplate.replace('/* TAG_GUIDE_STYLE */', () => guideStyle).replace('<!-- TAG_GUIDE_SCRIPT -->', () => `<script>\n${guideScript}\n</script>`);
if (await Bun.file(new URL("figma/plugin/ui.html", root)).text() !== expectedUI) throw new Error("Generated Figma UI is stale; run bun tools/build_figma.ts");
const { extract: exportFrame } = require("../figma/extract.js");
(globalThis as any).figma = { fileKey: "figlo-demo" };
const demo = JSON.stringify(exportFrame(demoFrame()), null, 2) + "\n";
if (await Bun.file(new URL("samples/demo.ir.json", root)).text() !== demo) throw new Error("Demo fixture is stale; run bun tools/generate_sample.ts");
const forbidden = new RegExp(["Frame", "wisp"].join(""), "i");
const glob = new Bun.Glob("**/*");
let checked = 0;
for await (const file of glob.scan({ cwd: fileURLToPath(root), dot: true, onlyFiles: true })) {
  if (/^(?:\.git|\.bak|out|build|node_modules|relay\/\.sessions)\//.test(file.replaceAll("\\", "/"))) continue;
  if (!/\.(?:js|ts|json|html|luau|py|md|toml|yml|yaml|svg|txt)$/.test(file) && file !== "LICENSE") continue;
  const content = await Bun.file(new URL(file.replaceAll("\\", "/"), root)).text();
  checked++;
  if (forbidden.test(content)) throw new Error("Release naming check failed: " + file);
  if (/-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----|gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|AKIA[0-9A-Z]{16}/.test(content)) throw new Error("Possible credential in " + file);
}
const manifest = await Bun.file(new URL("figma/plugin/manifest.json", root)).json();
if (manifest.name !== "Figlo" || manifest.main !== "code.js") throw new Error("Figma manifest mismatch");
if (checked < 30) throw new Error("Release scan did not cover the source tree");
console.log(`release: required files, generated Figma code, branding and credential patterns checked (${checked} files)`);
